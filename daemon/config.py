"""Paths, constants and user settings for the Touch Bar daemon.

Everything here must stay import-safe on a machine without a Touch Bar: the
preview tool imports the renderer and layout through the same modules.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

APP_ID = "ewweberlin.touchbar"

# The panel is 2170x60. tiny-dfr force-inserts an esc button at index 0 of both
# layers, which with Stretch = 23 puts our single stretched button at panel
# x = 91 with a width of 2079. All rendering happens in that canvas space.
PANEL_W = 2170
CANVAS_W = 2079
CANVAS_H = 60
CANVAS_X0 = 91

# Nine workspaces fit before the quick actions get too narrow to label.
MAX_WORKSPACES = 9


def _home() -> Path:
    return Path(os.environ.get("HOME", "~")).expanduser()


def _xdg(var: str, default: str) -> Path:
    value = os.environ.get(var)
    return Path(value).expanduser() if value else _home() / default


def _runtime_dir() -> Path:
    value = os.environ.get("XDG_RUNTIME_DIR")
    return Path(value) if value else Path(f"/run/user/{os.getuid()}")


STATE_DIR = _xdg("XDG_STATE_HOME", ".local/state") / "omarchy-touchbar"
CACHE_DIR = _xdg("XDG_CACHE_HOME", ".cache") / "omarchy-touchbar"
CONFIG_DIR = _xdg("XDG_CONFIG_HOME", ".config") / "omarchy-touchbar"
SETTINGS_PATH = CONFIG_DIR / "config.json"

# Theme switches are noticed by stat()ing colors.toml, but Omarchy's theme hook
# can ask for an immediate repaint by touching this file.
RUNTIME_DIR = _runtime_dir() / "omarchy-touchbar"
REFRESH_FILE = RUNTIME_DIR / "refresh"

THEME_COLORS = _home() / ".local/state/omarchy/current/theme/colors.toml"

TINY_DFR_DIR = Path("/etc/tiny-dfr")
TINY_DFR_CONFIG = TINY_DFR_DIR / "config.toml"
TINY_DFR_BASE_CONFIG = Path("/usr/share/tiny-dfr/config.toml")
# tiny-dfr runs as `nobody` with no home access, so the image has to live in a
# world-readable system path.
SVG_PATH = TINY_DFR_DIR / "omarchy-touchbar.svg"

HYPR_SOCKET_DIR = _runtime_dir() / "hypr"
HYPR_INSTANCE = os.environ.get("HYPRLAND_INSTANCE_SIGNATURE", "")

DEFAULT_SETTINGS: dict = {
    # Drawer auto-close, in milliseconds. 0 disables it.
    "idle_close_ms": 8000,
    # Maximum redraws per second. Every redraw is a full librsvg re-parse in
    # tiny-dfr, so this is a real budget, not a comfort setting.
    "max_fps": 12,
    # Slider resolution while dragging, in percent.
    "slider_step": 2,
    # Touch calibration. Set after first contact on real hardware if the
    # digitizer reports a mirrored or offset axis.
    "invert_x": False,
    "invert_y": False,
    "swap_xy": False,
    "x_offset": 0,
    # Stretch the digitizer's x range when it does not span the whole panel.
    "x_scale": 1.0,
    "y_offset": 0,
    # Workspaces shown on the left.
    "workspace_count": 5,
    "workspace_first": 1,
    # Show the app icon on window cards (a little slower to build, much faster
    # to scan).
    "window_icons": True,
    # Text labels under the quick-action icons. Off gives larger icons.
    "action_labels": True,
    # Icon size in px when action_labels is false (16-50).
    "action_icon_size": 34,
    "font_family": "Adwaita Sans, Noto Sans, Liberation Sans, sans-serif",
    # How long the strip keeps sampling every second after the last touch
    # before dropping to a slow poll (and then stopping entirely).
    "busy_seconds": 30,
    "sleep_seconds": 300,
}


CONFIG_MARKER = "# Generated by ewweberlin.touchbar."

# The media layer is a single stretched button whose SVG is our whole canvas.
# It must never carry an Action: tiny-dfr reloads the config on every repaint,
# which clears its touch map and would fire a half-pressed key.
STRETCH = 23


def config_text() -> str:
    """The /etc/tiny-dfr/config.toml we rewrite on every repaint.

    Uses the same PascalCase schema as the package's own config. The primary
    layer keeps Fn working exactly as it does without us; the media layer is
    just our canvas, so the Touch Bar is a pure display.
    """
    f_keys = "\n".join(
        f'    {{ Text = "F{n}", Action = "F{n}" }},' for n in range(1, 13)
    )
    return "\n".join(
        [
            CONFIG_MARKER,
            "# Rewritten whenever the strip repaints; local edits are lost.",
            "",
            "MediaLayerDefault = true",
            "ShowButtonOutlines = false",
            # Pixel shift moves the image under our hit zones, and it also
            # changes the computed button width.
            "EnablePixelShift = false",
            'FontTemplate = ":bold"',
            "AdaptiveBrightness = true",
            "ActiveBrightness = 255",
            "DoublePressSwitchLayers = 0",
            "",
            "MediaLayerKeys = [",
            f'    {{ Icon = "omarchy-touchbar", Stretch = {STRETCH}, '
            f"IconWidth = {CANVAS_W}, IconHeight = {CANVAS_H} }},",
            "]",
            "",
            "PrimaryLayerKeys = [",
            f_keys,
            "]",
            "",
        ]
    )


def load_settings() -> dict:
    settings = dict(DEFAULT_SETTINGS)
    try:
        raw = json.loads(SETTINGS_PATH.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return settings
    if isinstance(raw, dict):
        for key, value in raw.items():
            if key in settings and isinstance(value, (bool, int, float, str)):
                settings[key] = value
    count = settings.get("workspace_count")
    if isinstance(count, int) and not isinstance(count, bool):
        settings["workspace_count"] = max(1, min(MAX_WORKSPACES, count))
    return settings


def ensure_dirs() -> None:
    for path in (STATE_DIR, CACHE_DIR, CONFIG_DIR, RUNTIME_DIR):
        path.mkdir(parents=True, exist_ok=True)
